async function render() {
  const { execFileSync } = require("child_process");
  const py = (...args) => execFileSync(PYTHON, [path.join(HERE, "print_tools.py"), ...args], { stdio: "inherit" });
  py("fonts");

  const mockPath = path.join(HERE, "header-mock.html");
  fs.writeFileSync(mockPath, headerMock);
  const { chromium } = require(process.env.PLAYWRIGHT_MODULE || "playwright");
  const browser = await chromium.launch(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {});
  const page = await browser.newPage({ viewport: { width: 1120, height: 380 }, deviceScaleFactor: 3 });
  await page.goto("file://" + mockPath);
  await page.evaluate(() => document.fonts.ready);
  await page.screenshot({ path: path.join(HERE, "header-mock.png") });

  const variants = [
    ["office", 0, "297mm", "210mm"],
    ["print", BLEED, `${297 + 2 * BLEED_MM}mm`, `${210 + 2 * BLEED_MM}mm`],
  ];
  for (const [kind, bleed, width, height] of variants) {
    fs.writeFileSync(OUT_HTML, html(bleed));
    await page.goto("file://" + OUT_HTML);
    await page.evaluate(() => document.fonts.ready);
    await page.pdf({ path: OUT[kind], width, height, scale: SCALE, printBackground: true, margin: { top: 0, right: 0, bottom: 0, left: 0 } });
    py("finish", OUT[kind], String(bleed ? BLEED_MM : 0));
    console.log(`Wrote ${path.relative(ROOT, OUT[kind])} (${n} pages, ${width} x ${height})`);
  }
  await browser.close();
}

render().catch((e) => {
  console.error(e);
  process.exit(1);
});
