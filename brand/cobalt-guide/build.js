function swatch(key, big = false) {
  const [name, hex, use] = PALETTE[key];
  const [r, g, b] = rgb(hex);
  const [c, m, y, k] = cmyk(hex);
  const dark = lum(hex) < 0.4;
  return `<div class="sw ${big ? "big" : ""}">
    <div class="chipc" style="background:${hex};color:${dark ? "#fff" : "#111418"}${hex === "#FFFFFF" ? ";box-shadow:inset 0 0 0 1px #D9DDE8" : ""}"><b>${name}</b><span>${hex}</span></div>
    <dl><div><dt>RGB</dt><dd>${r} ${g} ${b}</dd></div><div><dt>CMYK</dt><dd>${c} ${m} ${y} ${k}</dd></div></dl>
    <p>${use}</p></div>`;
}

